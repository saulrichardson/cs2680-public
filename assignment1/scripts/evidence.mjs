import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import Database from 'better-sqlite3';

// Resolve every path relative to this script's own directory, so `pnpm evidence` works
// from `assignment1/` regardless of the caller's cwd.
const root = path.resolve(import.meta.dirname, '..');
const fixturesDir = path.join(root, 'fixtures');
const dbPath = path.join(root, '.data', 'mission-control.db');
const outPath = path.join(root, 'docs', 'evidence.md');

function analyze(name, lines, meta = {}) {
  const ev = lines.filter(Boolean).map((l) => {
    try {
      return JSON.parse(l);
    } catch {
      return { type: 'unparsed' };
    }
  });
  const init = ev.find((e) => e.type === 'system' && e.subtype === 'init') ?? {};
  const result = ev.find((e) => e.type === 'result') ?? {};
  const calls = new Map();
  for (const e of ev) {
    const blocks = Array.isArray(e.message?.content) ? e.message.content : [];
    for (const b of blocks) {
      if (b.type === 'tool_use')
        calls.set(b.id, {
          name: b.name,
          input: b.input,
          ts: Date.parse(e.timestamp ?? '') || null,
          parent: e.parent_tool_use_id ?? null,
        });
      if (b.type === 'tool_result' && calls.has(b.tool_use_id)) {
        const c = calls.get(b.tool_use_id);
        c.end = Date.parse(e.timestamp ?? '') || null;
        c.error = b.is_error === true;
      }
    }
  }
  const list = [...calls.values()].map((c) => ({ ...c, ms: c.ts && c.end ? c.end - c.ts : null }));
  // How deep delegation went: the longest `parent_tool_use_id` chain above any one call. 0 means a
  // flat run, 1 a subagent's own calls, 2 a subagent that delegated again. Walking stops at a
  // parent the recording does not contain (the hop still counts) and `seen` guards against a cycle.
  const depthOf = (id) => {
    const seen = new Set([id]);
    let depth = 0;
    let parent = calls.get(id)?.parent;
    while (parent && !seen.has(parent)) {
      depth += 1;
      seen.add(parent);
      parent = calls.get(parent)?.parent;
    }
    return depth;
  };
  const maxDepth = Math.max(0, ...[...calls.keys()].map(depthOf));
  const byName = {};
  for (const c of list) byName[c.name] = (byName[c.name] ?? 0) + 1;
  const longest = list
    .filter((c) => c.ms !== null)
    .sort((a, b) => b.ms - a.ms)
    .slice(0, 3);
  const stamps = ev.map((e) => Date.parse(e.timestamp ?? '')).filter((t) => !Number.isNaN(t));
  const wall = stamps.length ? Math.max(...stamps) - Math.min(...stamps) : null;
  const retries = ev.filter((e) => e.subtype === 'api_retry').length;
  const finalText =
    ev
      .filter((e) => e.type === 'assistant' && !e.parent_tool_use_id)
      .flatMap((e) => e.message?.content ?? [])
      .filter((b) => b.type === 'text')
      .at(-1)?.text ?? '';
  return `## ${name}

- prompt: ${JSON.stringify(meta.prompt ?? '(see fixture name)')}
- model: ${init.model ?? '?'} · permission mode: ${init.permissionMode ?? '?'} · Claude Code ${init.claude_code_version ?? '?'}
- events: ${ev.length} · tool calls: ${list.length} (${Object.entries(byName)
    .map(([k, v]) => `${k} ${v}`)
    .join(', ')}) · errors: ${list.filter((c) => c.error).length}
- subagent calls: ${list.filter((c) => c.name === 'Agent' || c.name === 'Task').length} · nested calls: ${list.filter((c) => c.parent).length} · max nesting depth: ${maxDepth}
- result: ${result.subtype ?? '?'} · turns ${result.num_turns ?? '?'} · cost $${Number(result.total_cost_usd ?? 0).toFixed(3)} · reported ${result.duration_ms ?? '?'} ms · timestamps span ${wall ?? '?'} ms · api retries ${retries}
- longest tool calls:
${longest.map((c) => `  - ${c.name} ${c.ms} ms: ${JSON.stringify(c.input).slice(0, 160)}`).join('\n') || '  - (no timings)'}
- final text (first 200 chars): ${JSON.stringify(finalText.slice(0, 200))}
`;
}

const out = [
  '# Evidence appendix',
  '',
  'Generated by `node scripts/evidence.mjs` from the recorded fixtures and the local database. Raw material only.',
  '',
];
for (const f of readdirSync(fixturesDir).filter((f) => f.endsWith('.jsonl') && !f.startsWith('synth')))
  out.push(analyze(`fixture ${f}`, readFileSync(path.join(fixturesDir, f), 'utf8').split('\n')));
if (existsSync(dbPath)) {
  try {
    const db = new Database(dbPath, { readonly: true });
    // Executions only: a replay or an import is a copy of a run that already appears here (or of
    // one recorded on another machine), and counting either would double the evidence.
    for (const run of db.prepare("select * from runs where origin = 'execution' order by started_at").all()) {
      const lines = db
        .prepare('select json from events where run_id = ? order by seq')
        .all(run.id)
        .map((r) => r.json);
      if (lines.length)
        out.push(
          analyze(`run ${run.id} (${new Date(run.started_at).toISOString()})`, lines, { prompt: run.prompt }),
        );
    }
  } catch (err) {
    console.log(`could not read ${dbPath}: ${err.message}`);
  }
}
writeFileSync(outPath, out.join('\n'));
console.log('wrote docs/evidence.md');
