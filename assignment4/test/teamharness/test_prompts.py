"""Frozen guidance is what continued agents read, even as maintained files evolve."""
from pathlib import Path
import hashlib
import json
import re
from tempfile import TemporaryDirectory
import unittest

from src.teamharness import prompts


class FrozenGuidanceTests(unittest.TestCase):
    def test_nested_library_links_provenance_and_frozen_bodies(self):
        source = prompts.GUIDES
        provenance = json.loads((source / 'provenance.json').read_text())
        for item in provenance['files']:
            installed = source / item['installed']
            self.assertEqual(hashlib.sha256(installed.read_bytes()).hexdigest(), item['installed_sha256'])
        # Relative cross-manual links must survive packaging and frozen copies.
        for chapter in source.rglob('*.md'):
            for link in re.findall(r'\]\(([^)]+)\)', chapter.read_text()):
                file = link.split('#', 1)[0]
                if file and '://' not in file:
                    self.assertTrue((chapter.parent / file).is_file(), (chapter, link))
        with TemporaryDirectory() as directory:
            saved = Path(directory) / 'guides'
            first = prompts.freeze_guides(saved)
            name=next(name for name in sorted(first) if name.endswith('.md'))
            body=saved/name
            self.assertEqual(hashlib.sha256(body.read_bytes()).hexdigest(),first[name])
            bytecode=saved/'__pycache__/generated.cpython-311.pyc'
            bytecode.parent.mkdir(exist_ok=True)
            bytecode.write_bytes(b'generated bytecode is not guidance')
            self.assertEqual(first, prompts.freeze_guides(saved))
            body.write_text(body.read_text() + '\nchanged source assumption\n')
            with self.assertRaisesRegex(ValueError, 'changed'):
                prompts.freeze_guides(saved)



if __name__ == "__main__":
    unittest.main()
