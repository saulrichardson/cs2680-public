def frozen_expectations(run, source, metadata):
    manifest = source / metadata['manifest']
    if file_digest(manifest) != metadata['manifest_sha256']:
        raise ValueError('Frozen manifest differs from sweep identity')
    entries = json.loads(manifest.read_text())
    expected = {entry['instance_id']: dict(entry, source_key=key) for key, entry in entries.items()
                if entry['instance_id'] in metadata['tasks']}
    if len(expected) != len(metadata['tasks']) or len(expected) != len(set(metadata['tasks'])):
        raise ValueError('Missing or duplicate sweep task identities')
    package = run / 'src.zip'
    arm = [arm for arm in metadata['arms'] if arm['name'] == 'teamharness']
    if len(arm) != 1 or file_digest(package) != arm[0]['sha256']:
        raise ValueError('Frozen package differs from sweep identity')
    with zipfile.ZipFile(package) as archive:
        files = {name: archive.read(name) for name in archive.namelist() if name.startswith('src/teamharness/')}
    guides = {name.removeprefix('src/teamharness/guides/'): hashlib.sha256(raw).hexdigest()
              for name, raw in files.items() if name.startswith('src/teamharness/guides/')
              and Path(name).name != 'manifest.json' and not name.endswith('.pyc')
              and '__pycache__' not in Path(name).parts}
    runtime = {Path(name).name: hashlib.sha256(raw).hexdigest() for name, raw in files.items()
               if Path(name).parent == Path('src/teamharness') and name.endswith('.py')}
    # Render with the frozen package's actual pure prompt function, not a second
    # hand-maintained approximation. No agent/session/provider is instantiated.
    # Resolve relative authored prompt modules from the same ZIP. Never import
    # a maintained working-copy module into an observation of a frozen campaign.
    loaded = {}
    def frozen_import(name, globals=None, locals=None, fromlist=(), level=0):
        if not level:
            return builtins.__import__(name, globals, locals, fromlist, level)
        if level != 1:
            raise ImportError('Frozen prompt import leaves its package')
        return load_prompt_module(name)
    def load_prompt_module(name):
        key = 'src/teamharness/' + name.replace('.', '/') + '.py'
        if key not in files:
            raise ImportError('Frozen prompt module missing: ' + key)
        if name not in loaded:
            module = types.ModuleType('frozen_prompt_reader.' + name)
            module.__file__ = str(run / key)
            module.__package__ = 'frozen_prompt_reader'
            module.__dict__['__builtins__'] = {**vars(builtins), '__import__': frozen_import}
            loaded[name] = module
            exec(compile(files[key], key, 'exec'), module.__dict__)
        return loaded[name]
    prompt_namespace = load_prompt_module('prompts').__dict__
    actual_root = Path('/work/teamharness-0/run/agents/guides')
    content = {name.removeprefix('src/teamharness/guides/'): raw for name, raw in files.items()
               if name.startswith('src/teamharness/guides/')
               and name.removeprefix('src/teamharness/guides/') in guides}
    if 'src/teamharness/guidance.py' in files:
        content = load_prompt_module('guidance').absolute_navigation(content, actual_root)
    guides = {name: hashlib.sha256(raw).hexdigest() for name, raw in content.items()}
    # Presence and content of the portable library affect the prompt. Render from
    # disposable copies of the frozen bytes, normalizing only their root spelling.
    with tempfile.TemporaryDirectory(prefix='frozen-prompt-') as temporary:
        root = Path(temporary).resolve()
        for name, raw in content.items():
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
        templates = {role: fingerprint(prompt_namespace['system_prompt'](
            role, Path('/__TEAM_WORKSPACE__'), guide_root=root).replace(str(root), str(actual_root)))
            for role in prompt_namespace['role_names']()}
    route = json.loads((source / metadata['route']).read_text())
    return expected, guides, runtime, templates, route['routes']['standard']['model']


