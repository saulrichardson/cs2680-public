    if plan_path.exists():
        plan = json.loads(plan_path.read_text())
        if file_digest(source / 'dev/fleet/fleet.py') != plan['controller_sha256']:
            raise ValueError('Frozen SSH controller differs from launch plan')
    controller = source / 'dev/fleet/fleet.py'
    fleet = types.ModuleType('owned_team_fleet')
    fleet.__file__ = str(controller)
    # Avoid importlib's bytecode cache writes inside the frozen source tree.
    exec(compile(controller.read_bytes(), str(controller), 'exec'), fleet.__dict__)
    directory = run / 'observations'
    directory.mkdir(exist_ok=True)
    cache_path = directory / 'archive-cache.json'
    cache = json.loads(cache_path.read_text()) if cache_path.exists() else {}
    collected = collected_summaries(sweep, expected, cache)
    code = HOST_CODE.replace('__EXPECTED__', repr(list(expected))).replace('__INNER__', repr(CONTAINER_CODE))
    def host_observation(host):
        if host.get('finished') or not host.get('ip'):
            return {'host': host['name'], 'rows': [], 'state': 'controller_finished' if host.get('finished') else 'awaiting_address'}
        try:
            answer = fleet.ssh(sweep, host, 'sudo python3 -', input=code, timeout=180)
            return {'host': host['name'], **json.loads(answer.stdout)}
        except Exception as error:
            return {'host': host['name'], 'rows': [], 'observation_error': type(error).__name__}
    with ThreadPoolExecutor(max_workers=min(4, max(1, len(metadata['hosts'])))) as pool:
        hosts = list(pool.map(host_observation, metadata['hosts']))
    rows = {iid: {'instance_id': iid, 'source': 'not_observed', 'state': 'not_observed'} for iid in expected}
    for host in hosts:
        for row in host['rows']:
            iid = row['instance_id']
            if iid not in expected:
                raise ValueError('Remote row is outside this sweep')
            rows[iid] = live_summary(row, expected[iid], guides, runtime, templates, physical_model)
    # Completed original-owner archives take precedence over absent containers.
    rows.update(collected)
    observed_at = time.time()
    values = list(rows.values())
    stamp = datetime.fromtimestamp(observed_at, timezone.utc).strftime('%Y%m%dT%H%M%S.%fZ')
    destination = directory / (stamp + '.json')
    history_path = directory / 'lifetime-evidence.json'
    history = json.loads(history_path.read_text()) if history_path.exists() else {}
    if any(iid not in expected for iid in history):
        raise ValueError('Prior lifetime evidence belongs to another sweep')
    merge_lifetimes(history, values, str(destination))
    summary = {'expected_tasks': len(expected), 'tasks_with_actual_requests': sum(bool(r.get('model_requests')) for r in values),
               'tasks_with_actual_responses': sum(bool(r.get('model_responses')) for r in values),
               'tasks_with_shell_results': sum(bool(r.get('shell_results_lower_bound')) for r in values),
               'workers_observed_active': sum(r.get('worker_active') is True for r in values),
               'workers_active_past_deadline': sum(r.get('worker_active') is True and r.get('deadline_remaining_seconds') is not None and r['deadline_remaining_seconds'] < 0 for r in values),
               'collected_archives': len(collected), 'model_lifetime_peak_lower_bound': lifetime_peak(history.values()),
               'live_tasks_with_verified_wire_contract': sum(r.get('checks', {}).get('all_observed_wire_contracts_match') is True for r in values),
               'live_tasks_with_physical_model_sample': sum(r.get('checks', {}).get('sampled_physical_model_matches') is True for r in values),
               'tasks_with_verified_shared_session_deadline': sum((r.get('deadline_evidence') or {}).get('verified') is True for r in values),
               'tasks_with_saved_wire_contract_evidence': sum('wire_contract_observation' in r for r in history.values()),
               'tasks_with_saved_physical_model_evidence': sum('physical_model_observation' in r for r in history.values()),
               'host_observation_errors': sum('observation_error' in h for h in hosts)}
    report = {'observed_at': observed_at, 'sweep': metadata['sweep'], 'expected_physical_model': physical_model,
              'summary': summary, 'tasks': values, 'host_observations': hosts, 'lifetime_evidence': history,
              'interpretation': 'Read-only observations, not controller actions. Lifetime overlap covers task execution between first actual request and confirmed later activity; it does not claim simultaneous HTTP inference. Shell counts deduplicate actual job receipts across direct/parallel results and saved epochs; work not yet returned to a session remains uncounted. Absent containers and read races are not repair failures.'}
    with destination.open('x') as out:
        json.dump(report, out, indent=2)
        out.write('\n')
    cache_path.write_text(json.dumps(cache, indent=2) + '\n')
    history_path.write_text(json.dumps(history, indent=2) + '\n')
    return destination, report


