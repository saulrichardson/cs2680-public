PUBLIC_FIELDS = ('problem_statement', 'requirements', 'interface')


def fingerprint(value):
    raw = json.dumps(value, sort_keys=True, ensure_ascii=False, separators=(',', ':')).encode()
    return hashlib.sha256(raw).hexdigest()


def public_task(task):
    return {key: task[key] for key in PUBLIC_FIELDS if key in task}


def guide_inventory(root):
    """Read authored nested guidance; generated bytecode is not library content."""
    root = Path(root)
    files, errors = {}, []
    if not root.is_dir():
        return files, [{'path': '.', 'error': 'Guide directory unavailable'}]
    for path in sorted(root.rglob('*')):
        relative = path.relative_to(root)
        if path.name == 'manifest.json' or path.suffix == '.pyc' or '__pycache__' in relative.parts:
            continue
        if path.is_symlink():
            errors.append({'path': str(relative), 'error': 'Unverified symbolic link'})
            continue
        try:
            if path.is_file():
                files[str(relative)] = hashlib.sha256(path.read_bytes()).hexdigest()
        except OSError as error:
            errors.append({'path': str(relative), 'error': type(error).__name__})
    return files, errors


def request_configuration(db, event):
    """Resolve an explicit request configuration without importing the runtime."""
    reference = event.get('config_ref')
    if reference is None:
        return None
    try:
        if not isinstance(reference, str) or not reference.startswith('obj:'):
            return False
        identity = int(reference[4:])
        row = db.execute("SELECT kind,body FROM objects WHERE id=? AND scope='session'", (identity,)).fetchone()
        if row is None or row[0] != 'session_configuration':
            return False
        saved = json.loads(row[1])
        config, request = saved['config'], event['request']
        expected_model = (event.get('provider_configuration') or {}).get('model') or saved.get('provider_model')
        return (saved['version'] == event.get('config_version')
                and request['messages'][0] == {'role': 'system', 'content': config['system']}
                and request['tools'] == config['tools']
                and all(request.get(key) == value for key, value in config.get('settings', {}).items())
                and (expected_model is None or request.get('model') == expected_model))
    except (KeyError, ValueError, TypeError, IndexError):
        return False


