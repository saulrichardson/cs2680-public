def collected_summaries(sweep, expected, cache):
    result = {}
    reporter_version = file_digest(Path(read_attempt.__code__.co_filename))
    for path in sorted(sweep.glob('hosts/*/results/teamharness/*.tar.zst')):
        iid = path.name.removesuffix('.tar.zst')
        if iid not in expected or iid in result:
            raise ValueError('Unexpected or duplicate native archive')
        stat = path.stat()
        identity = [str(path), stat.st_size, stat.st_mtime_ns, reporter_version, file_digest(Path(__file__))]
        prior = cache.get(iid, {})
        if prior.get('file_identity') != identity:
            try:
                entry = {k: v for k, v in expected[iid].items() if k != 'source_key'}
                environment = read_environment(path.parent.parent / 'validation/environment-checks.tar.zst', entry)
                summary = archive_summary(read_attempt(path, entry, environment))
            except Exception as error:
                summary = {'instance_id': iid, 'source': 'collected_archive', 'state': 'evidence_error',
                           'observation_error': type(error).__name__}
            cache[iid] = {'file_identity': identity, 'archive_sha256': file_digest(path), 'summary': summary}
        result[iid] = dict(cache[iid]['summary'], archive_sha256=cache[iid]['archive_sha256'])
    return result


def live_summary(row, expected, guides, runtime, templates, physical_model):
    native = row.get('native', {})
    sessions = native.get('sessions', [])
    starts = [s['first_transport_request_at'] for s in sessions if s.get('first_transport_request_at') is not None]
    ends = [s['last_transport_response_at'] for s in sessions if s.get('last_transport_response_at') is not None]
    if native.get('worker_active'):
        ends.append(native['observed_at'])
    public_hash = fingerprint(public_task(expected))
    checks = {'public_task_matches_manifest': row.get('public_task_sha256') == public_hash,
              'native_public_task_matches_manifest': native.get('public_task_sha256') == public_hash,
              'course_base_matches_manifest': row.get('launch', {}).get('course_base') == expected.get('base_commit'),
              'guides_match_package': native.get('guides') == guides,
              'guide_manifest_matches': native.get('guide_manifest_matches') is True,
              'role_templates_match_package': native.get('role_template_sha256') == templates,
              'runtime_files_match_package': native.get('runtime_files') == runtime}
    wire = [s for s in sessions if 'wire_system_matches_descriptor' in s]
    requesters = [s for s in sessions if s.get('model_requests', 0) or s.get('transport_requests', 0)]
    checks['all_observed_wire_contracts_match'] = (all(checks.values()) and bool(wire) and len(wire) == len(requesters)
        and not any(s.get('observation_error') for s in requesters) and all(
        ((s.get('wire_configuration_verified') is True and s.get('wire_request_matches_session') is True)
         if 'wire_configuration_verified' in s else
         (s.get('wire_system_matches_descriptor') and s.get('wire_tools_match_descriptor'))) and
        s.get('descriptor_matches_frozen_template') and s.get('descriptor_guides_match') for s in wire))
    physical = row.get('physical_requests_sample', [])
    checks['sampled_physical_model_matches'] = bool(physical) and all(r.get('model') == physical_model for r in physical)
    deadline = row.get('launch', {}).get('deadline')
    deadlines = deadline_evidence(sessions, deadline)
    checks['all_observed_session_deadlines_match'] = deadlines['verified']
    jobs = {job for session in sessions for job in session.get('shell_job_ids', [])}
    return {'instance_id': row['instance_id'], 'source': 'live', 'worker_active': native.get('worker_active'),
            'state': native.get('workflow_state'), 'session_count': len(sessions),
            'model_requests': sum(s.get('model_requests', 0) for s in sessions),
            'model_responses': sum(s.get('model_responses', 0) for s in sessions),
            'transport_requests': sum(s.get('transport_requests', 0) for s in sessions),
            'transport_responses': sum(s.get('transport_responses', 0) for s in sessions),
            'shell_results_lower_bound': len(jobs),
            'deadline_evidence': deadlines,
            'first_model_at': min(starts) if starts else None,
            'confirmed_alive_through': max(ends) if ends else None,
            'deadline': deadline, 'deadline_remaining_seconds': deadline-native['observed_at'] if deadline is not None and native.get('worker_active') else None,
            'checks': checks,
            'native_observation': row.get('native_observation'),
            'session_observation_errors': sum('observation_error' in s for s in sessions)}


def lifetime_peak(rows):
    events = []
    for row in rows:
        start, end = row.get('first_model_at'), row.get('confirmed_alive_through')
        if start is not None and end is not None and end > start:
            events.extend(((start, 1), (end, -1)))
    active = peak = 0
    for _, change in sorted(events):
        active += change
        peak = max(peak, active)
    return peak


def merge_lifetimes(history, rows, observation):
    for row in rows:
        start, end = row.get('first_model_at'), row.get('confirmed_alive_through')
        if start is None or end is None or end <= start:
            continue
        iid = row['instance_id']
        previous = history.get(iid, {})
        history[iid] = {**previous, 'instance_id': iid,
                       'first_model_at': min(start, previous.get('first_model_at', start)),
                       'confirmed_alive_through': max(end, previous.get('confirmed_alive_through', end)),
                       'latest_supporting_observation': observation}
        if row.get('checks', {}).get('all_observed_wire_contracts_match'):
            history[iid]['wire_contract_observation'] = observation
        if row.get('checks', {}).get('sampled_physical_model_matches'):
            history[iid]['physical_model_observation'] = observation
    return history


